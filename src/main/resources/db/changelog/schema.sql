CREATE TABLE staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(4) NOT NULL UNIQUE CHECK (code ~ '^[A-Za-z0-9]{4}$'),
    full_name VARCHAR(150) NOT NULL
);
CREATE TABLE pass_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL REFERENCES staff(id),
    full_name VARCHAR(150) NOT NULL,
    phone VARCHAR(12) NOT NULL,
    organization VARCHAR(150),
    purpose VARCHAR(200) NOT NULL,
    valid_from TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    valid_to TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
    comment VARCHAR(500),
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    CHECK (valid_to > valid_from AND valid_from::date = valid_to::date)
);
CREATE INDEX pass_request_host_time ON pass_request(host_id, valid_from, id);
